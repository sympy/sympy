from __future__ import annotations

from sympy.core.symbol import symbols
from sympy.core.numbers import I
from sympy.matrices.expressions import MatrixSymbol, Adjoint, Transpose
from sympy.matrices.expressions.conjugate import Conjugate
from sympy.matrices import Matrix
from sympy.assumptions import Q, assuming, refine
from sympy.testing.pytest import raises


def test_conjugate():
    n, m = symbols('n m', integer=True, positive=True)
    A = MatrixSymbol('A', n, m)
    B = MatrixSymbol('B', m, n)

    cA = Conjugate(A)
    assert cA.shape == (n, m)
    assert cA.arg == A

    # Inverse properties
    assert cA.conjugate() == A
    assert Conjugate(cA).doit() == A

    # Transposition and Adjoint duality
    assert cA.T == Adjoint(A)
    assert cA.transpose() == Adjoint(A)
    assert cA.adjoint() == A.T

    # Multiplication compatibility
    prod = cA * B
    assert prod.shape == (n, n)

    # Invalid input
    raises(TypeError, lambda: Conjugate(1))


def test_conjugate_klein_four_group():
    n, m = symbols('n m', integer=True, positive=True)
    A = MatrixSymbol('A', n, m)

    # The Klein 4-group generated by Transpose and Conjugate:
    # Transpose o Conjugate == Conjugate o Transpose == Adjoint
    assert Conjugate(A).transpose() == Adjoint(A)
    assert Conjugate(A).adjoint() == Transpose(A)
    assert Adjoint(A).transpose() == Conjugate(A)
    assert Adjoint(A).conjugate() == Transpose(A)


def test_conjugate_entry():
    M = Matrix([[1 + I, 2], [3 - 2*I, 4*I]])
    cM = Conjugate(M)
    assert cM.shape == (2, 2)
    assert cM[0, 0] == 1 - I
    assert cM[0, 1] == 2
    assert cM[1, 0] == 3 + 2*I
    assert cM[1, 1] == -4*I


def test_conjugate_refine():
    n = symbols('n', integer=True, positive=True)
    X = MatrixSymbol('X', n, n)
    with assuming(Q.real_elements(X)):
        assert refine(Conjugate(X)) == X


def test_conjugate_printing():
    from sympy import pretty, latex
    n = symbols('n', integer=True, positive=True)
    A = MatrixSymbol('A', n, n)
    cA = Conjugate(A)
    assert str(cA) == 'Conjugate(A)'
    assert latex(cA) == r'\overline{A}'
    assert '_' in pretty(cA)


def test_conjugate_matmul_matadd():
    from sympy import MatMul, MatAdd
    n = symbols('n', integer=True, positive=True)
    A = MatrixSymbol('A', n, n)
    B = MatrixSymbol('B', n, n)
    assert (A * B).conjugate() == Conjugate(A) * Conjugate(B)
    assert (I * A).conjugate() == -I * Conjugate(A)
    assert (A + B).conjugate() == Conjugate(A) + Conjugate(B)


def test_matpow_conjugate_issue_16498():
    from sympy.functions import adjoint, conjugate
    n = symbols('n', integer=True, positive=True)
    C = MatrixSymbol('C', n, n)
    B = MatrixSymbol('B', n, n)

    # Issue #16498: conjugate of negative / complex matrix power must not fail with AttributeError
    adj_inv = adjoint(C**(-2))
    assert isinstance(adj_inv, Conjugate)
    assert adj_inv.shape == (n, n)
    assert (adj_inv * B).shape == (n, n)

    adj_cmplx = adjoint(C**I)
    assert isinstance(adj_cmplx, Conjugate)
    assert adj_cmplx.shape == (n, n)

