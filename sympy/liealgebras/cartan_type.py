class CartanType_generator():
    """
    Constructor for actually creating things
    """
    def __call__(self, *args: str | list[str | int]) -> TypeA | TypeB | TypeC | TypeD | TypeE | TypeF | TypeG:
        c = args[0]
        if isinstance(c, list) and isinstance(c[0], str):
            letter, n = c[0], int(c[1])
        elif isinstance(c, str):
            letter, n = c[0], int(c[1:])
        else:
            raise TypeError("Argument must be a string (e.g. 'A3') or a list (e.g. ['A', 3])")

        if n < 0:
            raise ValueError("Lie algebra rank cannot be negative")
        if letter == "A":
            from . import type_a
            return type_a.TypeA(n)
        if letter == "B":
            from . import type_b
            return type_b.TypeB(n)

        if letter == "C":
            from . import type_c
            return type_c.TypeC(n)

        if letter == "D":
            from . import type_d
            return type_d.TypeD(n)

        if letter == "E":
            if n >= 6 and n <= 8:
                from . import type_e
                return type_e.TypeE(cast(Literal[6, 7, 8], n))

        if letter == "F":
            if n == 4:
                from . import type_f
                return type_f.TypeF(4)

        if letter == "G":
            if n == 2:
                from . import type_g
                return type_g.TypeG(2)

        raise ValueError(f"Invalid Cartan type: {letter}{n}")

CartanType = CartanType_generator()


class Standard_Cartan(Atom):
    """
    Concrete base class for Cartan types such as A4, etc
    """
    n: int
    _series: str

    def __new__(cls, series: str, n: int):
        obj = Basic.__new__(cls)
        obj.n = n
        obj._series = series
        return obj

    def rank(self) -> int:
        """
        Returns the rank of the Lie algebra
        """
        return self.n

    @property
    def series(self) -> str:
        """
        Returns the type of the Lie algebra
        """
        return self._series

    def simple_root(self, i: int) -> Matrix:
        raise NotImplementedError(
            "simple_root is implemented by subclasses of Standard_Cartan"
        )

    def positive_roots(self) -> dict[int, Matrix]:
        raise NotImplementedError(
            "positive_roots is implemented by subclasses of Standard_Cartan"
        )

    @final
    def cartan_matrix(self) -> Matrix:
        r"""
        Returns the Cartan Matrix for the algebra. For a
        given simple Lie algebra the elements $a_{ij}$ can be
        generated by

        .. math::
            a_{ji} = 2 \langle\alpha_i, \alpha_j\rangle / \langle\alpha_j, \alpha_j\rangle

        where $a_i$ is the i'th simple root and $\langle,\rangle$ is the scalar product.

        Sources
        =======
        - https://en.wikipedia.org/wiki/Cartan_matrix
        - https://mathworld.wolfram.com/CartanMatrix.html

        """
        n = self.rank()
        simple_roots = [self.simple_root(i) for i in range(1,n+1)]

        norms: list[int] | list[Rational] = [simple_roots[i].dot(simple_roots[i]) for i in range(n)] #type: ignore

        cartan_matrix: Matrix = 2*eye(n)
        for i in range(n):
            for j in range(i + 1, n):
                root_sum: Rational = 2*simple_roots[i].dot(simple_roots[j]) #type: ignore
                cartan_matrix[i, j] = root_sum / norms[j]
                cartan_matrix[j, i] = root_sum / norms[i]

        return cartan_matrix


    def dynkin_diagram(self) -> str:
        raise NotImplementedError(
            "dynkin_diagram is implemented by subclasses of Standard_Cartan"
        )
