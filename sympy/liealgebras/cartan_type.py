class CartanType_generator():
    """
    Constructor for actually creating things
    """
    def __call__(self, *args: str | list[str | int]) -> TypeA | TypeB | TypeC | TypeD | TypeE | TypeF | TypeG:
        c = args[0]
        if isinstance(c, list) and isinstance(c[0], str):
            letter, n = c[0], int(c[1])
        elif isinstance(c, str):
            letter, n = c[0], int(c[1:])
        else:
            raise TypeError("Argument must be a string (e.g. 'A3') or a list (e.g. ['A', 3])")

        if n < 0:
            raise ValueError("Lie algebra rank cannot be negative")
        if letter == "A":
            from . import type_a
            return type_a.TypeA(n)
        if letter == "B":
            from . import type_b
            return type_b.TypeB(n)

        if letter == "C":
            from . import type_c
            return type_c.TypeC(n)

        if letter == "D":
            from . import type_d
            return type_d.TypeD(n)

        if letter == "E":
            if n >= 6 and n <= 8:
                from . import type_e
                return type_e.TypeE(cast(Literal[6, 7, 8], n))

        if letter == "F":
            if n == 4:
                from . import type_f
                return type_f.TypeF(4)

        if letter == "G":
            if n == 2:
                from . import type_g
                return type_g.TypeG(2)

        raise ValueError(f"Invalid Cartan type: {letter}{n}")

CartanType = CartanType_generator()


class Standard_Cartan(Atom):
    """
    Concrete base class for Cartan types such as A4, etc
    """
    n: int
    _series: str

    def __new__(cls, series: str, n: int):
        obj = Basic.__new__(cls)
        obj.n = n
        obj._series = series
        return obj

    def rank(self) -> int:
        """
        Returns the rank of the Lie algebra
        """
        return self.n

    @property
    def series(self) -> str:
        """
        Returns the type of the Lie algebra
        """
        return self._series

    def simple_root(self, i: int) -> list[int] | list[Rational]:
        raise NotImplementedError(
            "simple_root is implemented by subclasses of Standard_Cartan"
        )

    def positive_roots(self) -> Mapping[int, list[int] | list[Rational]]:
        raise NotImplementedError(
            "positive_roots is implemented by subclasses of Standard_Cartan"
        )

    def cartan_matrix(self):
        """
        Returns the Cartan Matrix for the algebra. For a
        given simple Lie algabra the elements `a_ij` can be
        generated by

        a_ji = 2 <a_i, a_j> / <a_j, a_j>

        where a_i is the i'th simple root and <,> is the scalar product.
        """
        r = self.rank()
        cartan_matrix = zeros(r,r)
        for i, sr_i in enumerate(self.simple_roots()):
            for j, sr_j in enumerate(self.simple_roots()):
                cartan_matrix[j,i] = 2 * sr_i.dot(sr_j) / sr_i.dot(sr_i)
        return cartan_matrix

    def cocartan_matrix(self):
        """
        Returns the Cocartan matrix. The Cocartan matrix
        row elements, c_i, are built from covectors of simple roots, a_i.

        c_i = 2 a_i / <a_i, a_i>

        This relationship is helpful in defining the orthogonal base where
        multiplying by some weight, w_j, yields the unit matrix.

        <c_i, w_j> = KroneckerDelta[i,j].
        """
        return Matrix([
                2 * x / x.dot(x) for x in self.simple_roots()])

    def omega_matrix(self):
        """
        Returns the omega matrix, which rows are built from
        the fundamental weights of the algebra in the orthogonal
        basis.
        """
        return self.cocartan_matrix().pinv().T

    def dynkin_diagram(self) -> str:
        raise NotImplementedError(
            "dynkin_diagram is implemented by subclasses of Standard_Cartan"
        )

    def simple_roots(self):
        """
        Returns the simple roots of the algebra.
        """
        return [Matrix(self.simple_root(i+1)).T for i in range(self.n)]
